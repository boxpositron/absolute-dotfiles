const FOLDER = "\u{E5FF}";
const FOLDER_OPEN = "\u{E5FE}";
const SPECIAL_FOLDERS = { ".git": ["\u{E5FB}", "#F14C28"], node_modules: ["\u{E5FA}", "#8DC149"] };
const FILE = "\u{F4A5}";

// A Nerd Font for the glyphs, or "" when there is none. Nerd Fonts 2 (such as the "Complete" CaskaydiaCove)
// lack many of these glyphs and draw a box instead, and the Mono variants draw them a size smaller, so known
// full-size Nerd Fonts 3 families come first.
const PREFERRED = ["Symbols Nerd Font", "JetBrainsMono Nerd Font", "FiraCode Nerd Font", "Hack Nerd Font", "MesloLGM Nerd Font"];
let nerd = null;
function nerdFont() {
  if (nerd === null) {
    const have = fonts().filter((f) => /Nerd Font/.test(f));
    nerd = PREFERRED.find((f) => have.includes(f)) ?? have.find((f) => !/Caskaydia|Mono|Propo/.test(f)) ?? have.find((f) => !/Propo/.test(f)) ?? "";
  }
  return nerd;
}

function lookup(name, dir, open) {
  if (dir) return SPECIAL_FOLDERS[name] ?? [open ? FOLDER_OPEN : FOLDER, null];
  const lower = name.toLowerCase();
  if (BY_NAME[lower]) return BY_NAME[lower];
  for (let i = name.indexOf("."); i >= 0; i = name.indexOf(".", i + 1)) {
    const ext = name.slice(i + 1);
    const hit = BY_EXTENSION[ext] ?? BY_EXTENSION[ext.toLowerCase()];
    if (hit) return hit;
  }
  return [FILE, null];
}

// The icon for a file or folder name, `size` px, in its own colour or else `color` (the caller's dim text).
/** @param {string} name @param {{ dir?: boolean, open?: boolean, size?: number, color?: string }} [options] */
export function fileIcon(name, { dir = false, open = false, size = 14, color } = {}) {
  const font = nerdFont();
  if (!font) return svg(dir ? "mods/workspace-chrome/folder.svg" : "mods/workspace-chrome/file-text.svg").size(size).flex_none().text_color(color);
  const [glyph, own] = lookup(name, dir, open);
  return div().w(size + 4).flex_none().flex().items_center().justify_center().font_family(font).text_size(size).text_color(own ?? color).child(glyph);
}
